#!/usr/bin/env node
/**
 * Large-MR end-to-end harness.
 *
 * Runs a real `review-pi review` against the large-MR fixture, with a real
 * HTTP MCP server (scripts/e2e-mcp/server.mjs) recording every business tool
 * call. Afterwards it asserts the ADR-0061 contract:
 *
 *   - exactly one `mrReviewResult` per changed file, before the summary;
 *   - files without findings are still reported (`reviewTips: []`);
 *   - call order is startTask → mrReviewResult × N → saveReviewSummary → endTask;
 *   - the server state, `runs/mcp.json` and the dashboard agree.
 *
 * The user's `~/.PiAgent/PiAgent.jsonc` is read (never printed) and a copy with
 * an injected `mcp` block is written to `.tmp-gen/e2e-large-mr/`. The real user
 * config is not modified.
 *
 * Usage:
 *   node scripts/e2e-mcp/run-e2e.mjs [--server-url http://127.0.0.1:7317]
 */

import { spawn } from "node:child_process";
import { createRequire } from "node:module";
import {
  createWriteStream,
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..", "..");
const OUT_DIR = join(REPO_ROOT, ".tmp-gen", "e2e-large-mr");
const CONFIG_FILE = join(OUT_DIR, "PiAgent.e2e.jsonc");
const TASKS_DIR = join(OUT_DIR, "tasks");
const REPO_FIXTURE = join(REPO_ROOT, "packages", "review-pi", "testdata", "repos", "large-mr");
const DIFF_FILE = join(REPO_ROOT, "packages", "review-pi", "testdata", "e2e", "large-mr.diff");
const RULE_SKILL_ZIP = join(
  REPO_ROOT,
  "packages",
  "review-pi",
  "testdata",
  "rule-skills",
  "general-code-review.zip",
);
const CLI_ENTRY = join(REPO_ROOT, "packages", "review-pi", "bin", "review-pi.js");
const USER_CONFIG = join(homedir(), ".PiAgent", "PiAgent.jsonc");

const argv = process.argv.slice(2);
function argValue(name, fallback) {
  const index = argv.indexOf(name);
  return index >= 0 && argv[index + 1] !== undefined ? argv[index + 1] : fallback;
}
const SERVER_URL = (argValue("--server-url", "http://127.0.0.1:7317")).replace(/\/+$/, "");
const TASK_ID = argValue("--task-id", `e2e-large-mr-${new Date().toISOString().replace(/[:.]/g, "-")}`);

function fail(message) {
  console.error(`run-e2e: ${message}`);
  process.exit(1);
}

function log(message) {
  console.log(message);
}

function requireJsonc() {
  const requireFromPackage = createRequire(join(REPO_ROOT, "packages", "review-pi", "package.json"));
  try {
    return requireFromPackage("jsonc-parser");
  } catch {
    fail("jsonc-parser is not installed; run pnpm install first");
  }
}

function parseDiffFiles(text) {
  const files = [];
  for (const line of text.split("\n")) {
    if (!line.startsWith("diff --git ")) {
      continue;
    }
    const match = /^diff --git a\/(.+) b\/(.+)$/.exec(line);
    if (match === null) {
      fail(`unparsable diff header: ${line}`);
    }
    files.push(match[2]);
  }
  return files;
}

function prepareConfig() {
  if (!existsSync(USER_CONFIG)) {
    fail(`missing user config: ${USER_CONFIG}`);
  }
  const { parse } = requireJsonc();
  const text = readFileSync(USER_CONFIG, "utf8");
  const errors = [];
  const config = parse(text, errors, { allowTrailingComma: true, disallowComments: false });
  if (errors.length > 0) {
    fail(`cannot parse ${USER_CONFIG} (jsonc errors: ${errors.length})`);
  }
  if (config === null || typeof config !== "object") {
    fail(`${USER_CONFIG} is not an object`);
  }
  if (typeof config.reviewer?.apiKey !== "string" || config.reviewer.apiKey === "") {
    fail("reviewer.apiKey is missing in the user config");
  }
  config.mcp = {
    servers: {
      e2e: {
        transport: "http",
        handshake: "auto",
        url: `${SERVER_URL}/mcp`,
        headers: {},
        timeoutMs: 60_000,
      },
    },
    report: {
      server: "e2e",
      tool: "report_events",
      task: true,
      // keep the default include list (all event types)
      batch: { maxEvents: 50, maxDelayMs: 500 },
      flushTimeoutMs: 5_000,
      findings: "summary",
    },
  };
  mkdirSync(OUT_DIR, { recursive: true });
  const header = [
    "// Generated by scripts/e2e-mcp/run-e2e.mjs — do not edit, do not commit.",
    "// Contains the same secrets as ~/.PiAgent/PiAgent.jsonc; .tmp-gen/ is gitignored.",
    "",
  ].join("\n");
  writeFileSync(CONFIG_FILE, `${header}${JSON.stringify(config, null, 2)}\n`, "utf8");
  log(`config: ${CONFIG_FILE.replace(REPO_ROOT + "\\", "")}`);
}

async function httpJson(path, init) {
  const response = await fetch(`${SERVER_URL}${path}`, init);
  if (!response.ok) {
    throw new Error(`${path} → HTTP ${response.status}`);
  }
  return response.json();
}

async function checkServer() {
  try {
    const health = await httpJson("/api/health", { method: "GET" });
    log(`server: ${SERVER_URL} (${health.ok === true ? "ok" : "unexpected payload"})`);
  } catch (error) {
    fail(
      `MCP server is not reachable at ${SERVER_URL}: ${error.message}\n` +
        "  start it first: node scripts/e2e-mcp/server.mjs --port 7317",
    );
  }
}

function assertPrerequisites(diffFiles) {
  for (const path of [REPO_FIXTURE, DIFF_FILE, RULE_SKILL_ZIP, CLI_ENTRY]) {
    if (!existsSync(path)) {
      fail(`missing prerequisite: ${path}`);
    }
  }
  if (diffFiles.length === 0) {
    fail(`no files found in ${DIFF_FILE}`);
  }
  const cliCompiled = join(REPO_ROOT, "packages", "review-pi", "dist", "cli", "main.js");
  if (!existsSync(cliCompiled)) {
    fail("compiled CLI entry is missing; run pnpm build:presentation first");
  }
  const distMtime = statSync(cliCompiled).mtimeMs;
  for (const source of ["src/cli/main.ts", "src/mcp/report.ts", "src/mcp/task-tools.ts"]) {
    const full = join(REPO_ROOT, "packages", "review-pi", source);
    if (existsSync(full) && statSync(full).mtimeMs > distMtime) {
      fail(`compiled CLI is stale (${source} is newer); run pnpm build:presentation`);
    }
  }
}

function runCli() {
  const args = [
    CLI_ENTRY,
    "review",
    "--repo",
    REPO_FIXTURE,
    "--mr-diff",
    DIFF_FILE,
    "--rule-skill-zip",
    RULE_SKILL_ZIP,
    "--taskId",
    TASK_ID,
    "--tasks-dir",
    TASKS_DIR,
    "--config",
    CONFIG_FILE,
  ];
  mkdirSync(OUT_DIR, { recursive: true });
  const stdoutPath = join(OUT_DIR, "stdout.log");
  const stderrPath = join(OUT_DIR, "stderr.log");
  const stdoutFile = createWriteStream(stdoutPath, { flags: "w" });
  const stderrFile = createWriteStream(stderrPath, { flags: "w" });
  log(`task: ${TASK_ID}`);
  log(`command: node ${args.map((arg) => (arg.includes(" ") ? `"${arg}"` : arg)).join(" ")}`);
  log("--- review-pi live output ---");
  const startedAt = Date.now();
  const child = spawn(process.execPath, args, {
    cwd: REPO_ROOT,
    env: { ...process.env, NO_COLOR: "1" },
    stdio: ["ignore", "pipe", "pipe"],
  });
  child.stdout.on("data", (chunk) => {
    process.stdout.write(chunk);
    stdoutFile.write(chunk);
  });
  child.stderr.on("data", (chunk) => {
    process.stderr.write(chunk);
    stderrFile.write(chunk);
  });
  return new Promise((resolvePromise) => {
    child.on("close", (code) => {
      stdoutFile.end();
      stderrFile.end();
      resolvePromise({ code, durationMs: Date.now() - startedAt, stdoutPath, stderrPath });
    });
  });
}

function verifyState(state, diffFiles) {
  const problems = [];
  if (state.violations.length > 0) {
    for (const item of state.violations) problems.push(`order/violation: ${item}`);
  }
  const reported = state.files.map((file) => file.filePath);
  const missing = diffFiles.filter((file) => !reported.includes(file));
  const unexpected = reported.filter((file) => !diffFiles.includes(file));
  if (missing.length > 0) problems.push(`files never reported: ${missing.join(", ")}`);
  if (unexpected.length > 0) problems.push(`files reported but not in diff: ${unexpected.join(", ")}`);
  if (reported.length !== new Set(reported).size) problems.push("duplicate mrReviewResult for a file");

  const expectedOrder = ["startTask", ...diffFiles.map(() => "mrReviewResult"), "saveReviewSummary", "endTask"];
  const actualOrder = state.order;
  if (actualOrder.length !== expectedOrder.length || actualOrder.some((tool, index) => tool !== expectedOrder[index])) {
    problems.push(`call order mismatch: ${actualOrder.join(" → ")}`);
  }
  if (state.summary === null) problems.push("saveReviewSummary was never received");
  if (state.summary !== null && state.summary.markdownContent.trim() === "") {
    problems.push("saveReviewSummary.markdownContent is empty");
  }
  return problems;
}

function readJsonFile(path, label, problems) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    problems.push(`${label} unreadable: ${error.message}`);
    return undefined;
  }
}

function verifyArtifacts(state, diffFiles) {
  const problems = [];
  const runsDir = join(TASKS_DIR, TASK_ID, "runs");
  const mcpLog = readJsonFile(join(runsDir, "mcp.json"), "runs/mcp.json", problems);
  const reviewsEn = readJsonFile(join(runsDir, "reviews_en.json"), "runs/reviews_en.json", problems);
  const tipsPath = join(runsDir, "reviews_tips_zh.json");
  const tipsZh = existsSync(tipsPath) ? readJsonFile(tipsPath, "runs/reviews_tips_zh.json", problems) : undefined;

  if (mcpLog !== undefined) {
    const calls = Array.isArray(mcpLog.calls) ? mcpLog.calls : [];
    const reportFiles = calls.filter((call) => call.tool === "mrReviewResult").map((call) => call.input?.filePath);
    if (calls.length !== state.callCount) {
      problems.push(`runs/mcp.json has ${calls.length} calls but the server saw ${state.callCount}`);
    }
    const missing = diffFiles.filter((file) => !reportFiles.includes(file));
    if (missing.length > 0) problems.push(`runs/mcp.json missing files: ${missing.join(", ")}`);
    const failed = calls.filter((call) => call.ok !== true);
    if (failed.length > 0) problems.push(`runs/mcp.json contains ${failed.length} failed calls`);
  }
  if (reviewsEn !== undefined) {
    const findings = Array.isArray(reviewsEn) ? reviewsEn : reviewsEn.findings;
    if (!Array.isArray(findings)) problems.push("reviews_en.json has no findings array");
  }
  if (tipsZh !== undefined && !Array.isArray(tipsZh) && typeof tipsZh !== "object") {
    problems.push("reviews_tips_zh.json has an unexpected shape");
  }
  const logPath = join(runsDir, "review-pi.log");
  if (!existsSync(logPath)) problems.push("runs/review-pi.log missing");
  return { problems, mcpLog, reviewsEn, tipsZh, runsDir };
}

function printReport(state, diffFiles, run, artifacts) {
  const lines = [];
  lines.push("");
  lines.push("=== large-MR e2e report ===");
  lines.push(`taskId:            ${TASK_ID}`);
  lines.push(`exit code:         ${run.code}`);
  lines.push(`wall time:         ${(run.durationMs / 1000).toFixed(1)}s`);
  lines.push(`diff files:        ${diffFiles.length}`);
  lines.push(`business calls:    ${state.callCount} (server) / ${artifacts.mcpLog?.calls?.length ?? "?"} (mcp.json)`);
  lines.push(`reported files:    ${state.files.length}`);
  lines.push(`files w/o tips:    ${state.counts.emptyFiles}`);
  lines.push(`tips total:        ${state.counts.tips}`);
  lines.push(`progress events:   ${state.counts.progressEvents} across ${state.counts.progressStreams} stream(s)`);
  lines.push(`handshakes:        ${state.handshakes}`);
  lines.push("");
  lines.push("file coverage (mrReviewResult order):");
  state.files.forEach((file, index) => {
    const levels = file.reviewTips.map((tip) => tip.level ?? "?").join(",");
    lines.push(
      `  ${String(index + 1).padStart(2, "0")}. ${file.filePath}  tips=${file.reviewTips.length}` +
        (levels === "" ? "  (reviewTips: [])" : `  levels=${levels}`),
    );
  });
  lines.push("");
  lines.push("call order:");
  lines.push(`  ${state.order.join(" → ")}`);
  lines.push("");
  lines.push("artifacts:");
  lines.push(`  ${join(artifacts.runsDir, "mcp.json")}`);
  lines.push(`  ${join(artifacts.runsDir, "reviews_en.json")}`);
  lines.push(`  ${join(artifacts.runsDir, "reviews_tips_zh.json")}`);
  lines.push(`  ${join(artifacts.runsDir, "review-pi.log")}`);
  lines.push(`  ${run.stdoutPath}`);
  lines.push(`  ${run.stderrPath}`);
  lines.push("");
  lines.push(`dashboard: ${SERVER_URL}/`);
  lines.push("===========================");
  return lines.join("\n");
}

async function main() {
  log("large-MR e2e: preparing");
  const diffText = readFileSync(DIFF_FILE, "utf8");
  const diffFiles = parseDiffFiles(diffText);
  log(`diff: ${diffFiles.length} files, ${diffText.length} chars`);
  assertPrerequisites(diffFiles);
  await checkServer();
  prepareConfig();

  await httpJson("/api/reset", { method: "POST", body: "{}" });
  await httpJson("/api/expect", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ files: diffFiles, taskId: TASK_ID, caseId: "large-mr" }),
  });
  log(`expect: ${diffFiles.length} files`);

  const run = await runCli();
  log("--- review-pi finished ---");
  if (run.code !== 0) {
    log(`review-pi exited with ${run.code}; stderr: ${run.stderrPath}`);
  }

  const state = await httpJson("/api/state", { method: "GET" });
  const problems = verifyState(state, diffFiles);
  const artifacts = verifyArtifacts(state, diffFiles);
  problems.push(...artifacts.problems);

  log(printReport(state, diffFiles, run, artifacts));

  if (problems.length > 0) {
    console.error("");
    console.error("e2e assertions FAILED:");
    for (const problem of problems) console.error(`  - ${problem}`);
    process.exitCode = 1;
    return;
  }
  log("");
  log("e2e assertions PASSED: every changed file reported before the summary.");
}

try {
  await main();
} catch (error) {
  console.error(error instanceof Error ? error.stack ?? error.message : String(error));
  process.exitCode = 1;
}
